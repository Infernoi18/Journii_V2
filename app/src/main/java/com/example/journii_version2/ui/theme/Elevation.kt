package com.example.journii_version2.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Elevation scale for the "soft elevation" cards called for in the design
 * spec — deliberately subtle. Journii's depth comes from shadows and warm
 * surface tones, not harsh Material drop-shadows.
 */
object JourniiElevation {
    val none: Dp = 0.dp
    val low: Dp = 2.dp
    val medium: Dp = 6.dp
    val high: Dp = 12.dp
}
